def load_extra(path):
    """本ごとの語を足す。TSV（1行に「語<TAB>読み」。送り仮名のある語は「泣き別れ<TAB>な|き|わか|れ」のように、
    漢字の部分の読みと送り仮名を | で交互に書く）"""
    out = []
    for line in Path(path).read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        word, yomi = line.split("\t")[:2]
        parts = yomi.split("|")
        if len(parts) == 1:
            out.append((word, r(word, yomi), ""))
            continue
        # 漢字の連なりと送り仮名に分け、漢字の連なりに順に読みを当てる
        chunks = re.findall(r"[\u4e00-\u9fff々亖]+|[^\u4e00-\u9fff々亖]+", word)
        rep, k = "", 0
        for c in chunks:
            if re.match(r"[\u4e00-\u9fff々亖]", c):
                rep += r(c, parts[k]); k += 2
            else:
                rep += c
        out.append((word, rep, ""))
    return out

# ルビを振らない部分（コード・タグ・既にあるルビ・VFMのルビ・front matter・URL）
PROTECT = re.compile(
    r"(\A---\n.*?\n---\n"            # front matter
    r"|```.*?```"                     # コードの囲み
    r"|`[^`\n]*`"                     # インラインのコード
    r"|<ruby>.*?</ruby>"              # 既にあるルビ
    r"|\{[^{}|\n]+\|[^{}\n]+\}"       # VFM のルビ
    r"|<[^>]+>"                       # HTML のタグ（属性の中の文字を含む）
    r"|https?://\S+)", re.S)


def process(text):
    parts = PROTECT.split(text)   # 偶数番目が地の文、奇数番目が守る部分
    done = []
    for term, rep, ng in sorted(TERMS, key=lambda t: -len(t[0])):
        pat = re.compile((f"(?<![{re.escape(ng)}])" if ng else "") + re.escape(term))
        for i in range(0, len(parts), 2):
            m = pat.search(parts[i])
            if m:
                # 置き換えた部分は、以後の語で再び触らないよう、守る部分として分ける
                before, after = parts[i][:m.start()], parts[i][m.end():]
                parts[i:i + 1] = [before, rep, after]
                done.append(term)
                break
    return "".join(parts), done


def main():
    argv = sys.argv[1:]
    dry = "--dry-run" in argv
    terms, skip, files, i = list(TERMS), [], [], 0
    while i < len(argv):
        a = argv[i]
        if a == "--terms":
            terms += load_extra(argv[i + 1]); i += 2; continue
        if a == "--skip":
            i += 1
            while i < len(argv) and not argv[i].startswith("--"):
                skip.append(argv[i]); i += 1
            continue
        if not a.startswith("--"):
            files.append(Path(a))
        i += 1
    TERMS[:] = terms
    files = files or sorted(Path("draft").glob("*.md"))
    for f in files:
        if f.name.startswith(tuple(skip)):
            continue
        text = f.read_text()
        new, done = process(text)
        if done:
            print(f"{f.name}: {len(done)}語　{'・'.join(done)}")
            if not dry:
                f.write_text(new)


if __name__ == "__main__":
    main()
